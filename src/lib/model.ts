export interface Game {
  id: string;
  season: number;
  week: number;
  /** ISO calendar date (YYYY-MM-DD). A modeled Saturday, never a kickoff moment. */
  date: string;
  weekLabel: string;
  /** Administrative home/away designations. At neutral sites these are accounting labels only. */
  home: string;
  away: string;
  homeSlug: string;
  awaySlug: string;
  homeIsPower: boolean;
  awayIsPower: boolean;
  /** Each school's own affiliation (Power conference, Independent, or G6 league). */
  homeConference: string;
  awayConference: string;
  type: GameType;
  /** The raw `Conference` column: the conference associated with the game/category, not a team's league. */
  categoryConference: string;
  venue: string;
  siteType: SiteType;
  isNeutral: boolean;
  status: RawStatus;
  statusLabel: string;
  provenance: Provenance;
  /** Only set when the raw `Source URL` is a valid http(s) URL. */
  sourceUrl: string | null;
  /** Non-URL explanatory text found in the raw `Source URL` column. */
  sourceNote: string | null;
  requestedWeek: number | null;
  /** Reference to the untouched input record, for audit. */
  raw: RawGame;
}

/** A game as seen from one participant's schedule. */
export interface TeamGame {
  game: Game;
  team: string;
  opponent: string;
  opponentSlug: string;
  opponentIsPower: boolean;
  opponentConference: string;
  /** H / A, or N when Site type is Neutral (regardless of administrative designation). */
  site: "H" | "A" | "N";
  /** Administrative designation for this team even at neutral sites. */
  adminSide: "home" | "away";
}

export function isHttpUrl(s: string | null | undefined): s is string {
  if (!s) return false;
  const t = s.trim();
  if (!/^https?:\/\//i.test(t)) return false;
  try {
    const u = new URL(t);
    return (u.protocol === "http:" || u.protocol === "https:") && !!u.hostname;
  } catch {
    return false;
  }
}

function assertOneOf<T extends string>(value: string, allowed: readonly T[], field: string, id: string): T {
  if (!(allowed as readonly string[]).includes(value)) {
    throw new Error(`Game ${id}: unexpected ${field} "${value}" (allowed: ${allowed.join(", ")})`);
  }
  return value as T;
}

const ISO_DATE = /^\d{4}-\d{2}-\d{2}$/;

export function normalizeGame(raw: RawGame): Game {
  const id = raw["Game ID"];
  for (const k of RAW_KEYS) {
    if (!(k in raw)) throw new Error(`Game ${id ?? "?"}: missing key "${k}"`);
  }
  const type = assertOneOf(raw.Type, GAME_TYPES, "Type", id);
  const siteType = assertOneOf(raw["Site type"], SITE_TYPES, "Site type", id);
  const status = assertOneOf(raw.Status, RAW_STATUSES, "Status", id);
  if (!Number.isInteger(raw.Week)) throw new Error(`Game ${id}: non-integer week ${raw.Week}`);
  if (!ISO_DATE.test(raw.Date)) throw new Error(`Game ${id}: invalid date ${raw.Date}`);
  for (const t of [raw.Home, raw.Away]) {
    if (!POWER_BY_NAME.has(t) && !G6_BY_NAME.has(t)) throw new Error(`Game ${id}: unknown program "${t}"`);
  }
  const src = (raw["Source URL"] ?? "").trim();
  const info = STATUS_INFO[status];
  return {
    id,
    season: raw.Year,
    week: raw.Week,
    date: raw.Date,
    weekLabel: raw["Week label"],
    home: raw.Home,
    away: raw.Away,
    homeSlug: slugify(raw.Home),
    awaySlug: slugify(raw.Away),
    homeIsPower: isPowerTeam(raw.Home),
    awayIsPower: isPowerTeam(raw.Away),
    homeConference: affiliationOf(raw.Home),
    awayConference: affiliationOf(raw.Away),
    type,
    categoryConference: raw.Conference,
    venue: raw.Venue,
    siteType,
    isNeutral: siteType === "Neutral",
    status,
    statusLabel: info.label,
    provenance: info.provenance,
    sourceUrl: isHttpUrl(src) ? src : null,
    sourceNote: src && !isHttpUrl(src) ? src : null,
    requestedWeek: raw["Requested week"],
    raw,
  };
}

export function teamView(game: Game, team: string): TeamGame {
  const isHome = game.home === team;
  if (!isHome && game.away !== team) throw new Error(`${team} is not in game ${game.id}`);
  const opponent = isHome ? game.away : game.home;
  return {
    game,
    team,
    opponent,
    opponentSlug: isHome ? game.awaySlug : game.homeSlug,
    opponentIsPower: isHome ? game.awayIsPower : game.homeIsPower,
    opponentConference: isHome ? game.awayConference : game.homeConference,
    site: game.isNeutral ? "N" : isHome ? "H" : "A",
    adminSide: isHome ? "home" : "away",
  };
}

/** Parse an ISO calendar date without timezone conversion. */
export function parseIsoDate(iso: string): { y: number; m: number; d: number } {
  const [y, m, d] = iso.split("-").map(Number);
  return { y, m, d };
}

const MONTHS = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];
const WEEKDAYS = ["Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat"];

/** Format a calendar date ("Sat, Aug 28, 2027") using UTC math so no timezone can shift the day. */
export function formatDate(iso: string, opts: { weekday?: boolean; year?: boolean } = {}): string {
  const { y, m, d } = parseIsoDate(iso);
  const wd = new Date(Date.UTC(y, m - 1, d)).getUTCDay();
  const core = `${MONTHS[m - 1]} ${d}`;
  return `${opts.weekday === false ? "" : WEEKDAYS[wd] + ", "}${core}${opts.year === false ? "" : `, ${y}`}`;
}

/** Next calendar day as ISO date (UTC arithmetic). */
export function nextDay(iso: string): string {
  const { y, m, d } = parseIsoDate(iso);
  const dt = new Date(Date.UTC(y, m - 1, d + 1));
  return dt.toISOString().slice(0, 10);
}

export function pairKey(a: string, b: string): string {
  return [a, b].sort().join("|");
}

